/**
 * English — the source of truth for the key set.
 *
 * `Translations` is derived from this object, so every other dictionary is
 * checked against it at build time: a missing key, a stray key, or a plural
 * entry where a plain string belongs all fail to compile.
 *
 * Keys read `area.thing`, where the area is the screen or the concept rather
 * than the component, so a string used in three places still has one home.
 * `{name}` placeholders are substituted at call time; entries written as
 * `{ one, other }` pick a form from the `count` parameter.
 */

/** A key whose text depends on a count. `other` covers every non-singular case. */
export interface PluralForms {
  one: string;
  other: string;
}

